@st.dialog("📖 모임 정산 프로그램 도움말", width="large")
def show_help_dialog() -> None:
    """
    세부 도움말 팝업을 그립니다. (st.dialog 데코레이터로 호출 시 팝업으로 열림)
    HELP_TABS의 항목을 순서대로 탭으로 보여 주며, 팝업은 X 버튼이나 ESC 키로 닫힙니다.
    """
    tabs = st.tabs([title for title, _ in HELP_TABS])
    for tab, (_, body) in zip(tabs, HELP_TABS):
        with tab:
            st.markdown(body)


def render_help_button() -> None:
    """
    사이드바 맨 위(화면 왼쪽 상단)에 '❓ 도움말' 버튼을 배치합니다.
    클릭하면 show_help_dialog() 팝업을 엽니다. 다른 사이드바 요소보다 먼저 호출해야 맨 위에 놓입니다.
    """
    if st.sidebar.button("❓ 도움말", key="help_btn", help="사용 방법을 팝업으로 봅니다."):
        print("[blue]도움말 팝업 열기[/blue]")
        show_help_dialog()
